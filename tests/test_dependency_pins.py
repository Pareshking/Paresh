"""Runtime dependencies are pinned to the exact versions CI tested (TODO S209).

A floor such as `pandas>=2.0.0` let Streamlit Cloud install whatever was newest
on the day a container booted, while the suite had only ever run against one
version. Since S209 the hand-edited list is requirements.in (boto3 stays a range
there on purpose) and requirements.txt is compiled from it by `uv pip compile`,
so every package, the dependencies of dependencies included, is pinned.
"""

import re
from pathlib import Path

import yaml
from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[1]
RANGED_ON_PURPOSE = {"boto3"}


def _specs(name: str) -> list[str]:
    out = []
    for line in (ROOT / name).read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            out.append(line)
    return out


def _compiled() -> dict[str, Requirement]:
    return {Requirement(s).name.lower(): Requirement(s) for s in _specs("requirements.txt")}


def test_every_installed_package_is_pinned_exactly():
    loose = [
        str(req) for req in _compiled().values()
        if len(req.specifier) != 1 or next(iter(req.specifier)).operator != "=="
    ]
    assert not loose, f"requirements.txt must pin exactly; regenerate it from requirements.in: {loose}"


def test_the_compiled_file_satisfies_every_hand_edited_requirement():
    """A requirements.in edit without a recompile leaves the two files disagreeing."""
    compiled = _compiled()
    stale = []
    for spec in _specs("requirements.in"):
        want = Requirement(spec)
        got = compiled.get(want.name.lower())
        pinned = next(iter(got.specifier)).version if got else None
        if pinned is None or not want.specifier.contains(pinned, prereleases=True):
            stale.append(f"{spec} -> {pinned}")
    assert not stale, f"run the uv pip compile command in requirements.in: {stale}"


def test_only_the_named_ranges_are_ranges_in_the_hand_edited_file():
    ranged = [
        spec for spec in _specs("requirements.in")
        if Requirement(spec).name.lower() not in RANGED_ON_PURPOSE
        and not re.fullmatch(r"[A-Za-z0-9_.-]+==[0-9][0-9A-Za-z.]*", spec)
    ]
    assert not ranged, f"pin these in requirements.in too, or name them in RANGED_ON_PURPOSE: {ranged}"


def test_the_compiled_file_says_how_it_was_made():
    head = (ROOT / "requirements.txt").read_text(encoding="utf-8").splitlines()[:2]
    assert "autogenerated by uv" in head[0]
    assert "uv pip compile requirements.in --universal --python-version 3.14" in head[1]


def test_the_r2_gate_skips_dependabot_prs_and_reruns_on_main():
    wf = yaml.safe_load(
        (ROOT / ".github/workflows/r2-streamlit-production-gate.yml").read_text()
    )
    # PyYAML reads the bare `on:` key as True.
    push_paths = wf[True]["push"]["paths"]
    assert "requirements.txt" in push_paths
    guard = wf["jobs"]["gate"]["if"]
    assert "dependabot[bot]" in guard and "pull_request" in guard
